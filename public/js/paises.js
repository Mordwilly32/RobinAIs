// Llena un <select> con la lista entera. La primera opción es la que obliga a
// elegir: un desplegable que arranca en «Afganistán» se envía sin querer.
function rrLlenarPaises(select, { elegido = '' } = {}) {
  if (!select) return;
  select.innerHTML = '<option value="">Elige tu país…</option>';
  RR_PAISES.forEach(([codigo, nombre]) => {
    const opt = document.createElement('option');
    opt.value = nombre;
    opt.dataset.codigo = codigo;
    opt.textContent = nombre;
    if (nombre === elegido) opt.selected = true;
    select.appendChild(opt);
  });
}
